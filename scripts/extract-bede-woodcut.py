"""Extract the existing paths, fills and printed labels; never redraw the artwork."""
from pathlib import Path
import json
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
source = ROOT / 'public/reference/hands/finger-numerals-1520.svg'
paths = [p for p in ET.parse(source).getroot() if p.tag.endswith('path')]
# Figure centers differ slightly between the four printed rows.
centers = [
    [117, 252, 391, 532, 671, 811, 952, 1092, 1234],
    [106, 253, 394, 535, 679, 826, 964, 1102, 1243],
    [117, 261, 404, 547, 682, 828, 972, 1114, 1257],
    [118, 257, 407, 550, 692, 833, 974, 1116, 1256],
]
cells = {10 ** row * digit: [] for row in range(4) for digit in range(1, 10)}
for path in paths:
    d = path.attrib['d']
    assert set(re.findall('[A-Za-z]', d)) <= set('MLCZ')
    numbers = list(map(float, re.findall(r'-?\d+(?:\.\d+)?', d)))
    xs, ys = numbers[::2], numbers[1::2]
    x, y = (min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2
    row = next((i for i, end in enumerate([199, 372, 543, 743]) if y < end), 3)
    col = min(range(9), key=lambda i: abs(x - centers[row][i]))
    # These three small contour details sit left of the 9000 figure's center.
    if path.attrib['id'] in {'path23899', 'path24019', 'path24241'}:
        row, col = 3, 8
    cells[10 ** row * (col + 1)].append({'d': d, 'fill': True, 'color': path.attrib['fill']})

# Each panel retains the original coordinates. A viewBox performs the crop;
# path data, order, colors, hatching and printed numerals remain unchanged.
output = {}
for value, cell in cells.items():
    coords = [list(map(float, re.findall(r'-?\d+(?:\.\d+)?', p['d']))) for p in cell]
    xs = [x for c in coords for x in c[::2]]
    ys = [y for c in coords for y in c[1::2]]
    left, top = min(xs) - 4, min(ys) - 4
    width, height = max(xs) - left + 4, max(ys) - top + 4
    output[value] = {'viewBox': ' '.join(f'{v:.2f}' for v in [left, top, width, height]), 'paths': cell}

(ROOT / 'src/glyphs/bede-woodcut.ts').write_text(
    '// Generated by scripts/extract-bede-woodcut.py. Original source paths and fills.\n'
    '// Public domain: https://commons.wikimedia.org/wiki/File:Finger_numerals_1520-Bedan_system.svg\n'
    'import type { GlyphPath } from "../lib/types";\n'
    'export const woodcutCells: Record<number, { viewBox: string; paths: GlyphPath[] }> = '
    + json.dumps(output, separators=(',', ':')) + ';\n'
)
print(f'Extracted all {len(paths)} unchanged source paths into {len(cells)} numbered panels.')
