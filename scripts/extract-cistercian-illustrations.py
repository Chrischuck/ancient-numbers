"""Package sourced artwork without redrawing hands or regenerating the scans."""
from pathlib import Path
import base64
import json
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
assets = ROOT / 'public/reference/hands'
widths = [98, 113, 111, 123, 117]
figures = {}
for number, width in enumerate(widths, 1):
    data = (assets / f'hour-count-{number}.jpg').read_bytes()
    figures[number] = {'href': 'data:image/jpeg;base64,' + base64.b64encode(data).decode(), 'width': width, 'height': 172, 'print': True}
detail = {'href': 'data:image/jpeg;base64,' + base64.b64encode((assets / 'hour-finger-detail.jpg').read_bytes()).decode(), 'width': 98, 'height': 133, 'print': True}
root = ET.parse(assets / 'counting-fingers-on-hand.svg').getroot()
count_paths = [{'d': p.attrib['d'], 'fill': True, 'color': '#000000'} for p in root.iter() if p.tag.endswith('path')]
source = '// Generated by scripts/extract-cistercian-illustrations.py. Existing source artwork, not redrawn.\n'
source += 'import type { GlyphDefinition, GlyphPath } from "../lib/types";\n'
source += 'export const hourFigures: Record<number, NonNullable<GlyphDefinition["images"]>[number]> = ' + json.dumps(figures, separators=(',', ':')) + ';\n'
source += 'export const fingerDetail: NonNullable<GlyphDefinition["images"]>[number] = ' + json.dumps(detail, separators=(',', ':')) + ';\n'
source += 'export const countingPaths: GlyphPath[] = ' + json.dumps(count_paths, separators=(',', ':')) + ';\n'
(ROOT / 'src/glyphs/cistercian-illustrations.ts').write_text(source)
print('Packaged five original engraved figures, a finger detail and the original counting-action path.')
