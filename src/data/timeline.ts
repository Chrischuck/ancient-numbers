/** Curated historical events. Negative years are BCE; there is no year zero.
 * A period's end is an evidence/usage boundary, never a claim of universal extinction.
 */
export type TimelineKind = 'numerals' | 'notation' | 'milestone';
export type TimelineStatus = 'living' | 'historical' | 'event';
export interface TimelineSource {
  title: string;
  url: string;
}
export interface TimelineEntry {
  id: string;
  year: number;
  date: string;
  title: string;
  kind: TimelineKind;
  place: string;
  symbol: string;
  summary: string;
  detail: string;
  status: TimelineStatus;
  usage: string;
  end?: number;
  system?: string;
  sources: TimelineSource[];
}
const topic = (slug: string, title: string): TimelineSource => ({
  title: `MacTutor — ${title}`,
  url: `https://mathshistory.st-andrews.ac.uk/HistTopics/${slug}/`,
});
const bio = (slug: string, name: string): TimelineSource => ({
  title: `MacTutor — ${name}`,
  url: `https://mathshistory.st-andrews.ac.uk/Biographies/${slug}/`,
});
const symbols = (slug: string, title: string): TimelineSource => ({
  title: `Jeff Miller / MacTutor — ${title}`,
  url: `https://mathshistory.st-andrews.ac.uk/Miller/mathsym/${slug}/`,
});
const operation = symbols('operation', 'Symbols of operation');
const relation = symbols('relation', 'Symbols of relation');
const constants = symbols('constants', 'Symbols for constants');
const functions = symbols('functions', 'Function symbols');
const calculus = symbols('calculus', 'Symbols of calculus');
const sets = symbols('set', 'Set theory and logic');
const notation = (
  id: string,
  year: number,
  title: string,
  symbol: string,
  place: string,
  summary: string,
  detail: string,
  source: TimelineSource,
): TimelineEntry => ({
  id,
  year,
  date: String(year),
  title,
  symbol,
  place,
  summary,
  detail,
  kind: 'notation',
  status: 'living',
  usage: 'Still in use',
  sources: [source],
});
const milestone = (
  id: string,
  year: number,
  date: string,
  title: string,
  symbol: string,
  place: string,
  summary: string,
  detail: string,
  source: TimelineSource,
): TimelineEntry => ({
  id,
  year,
  date,
  title,
  symbol,
  place,
  summary,
  detail,
  kind: 'milestone',
  status: 'event',
  usage: 'Dated milestone',
  sources: [source],
});
